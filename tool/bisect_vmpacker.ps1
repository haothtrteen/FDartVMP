# bisect_vmpacker.ps1 - which of the three new VMPacker targets computes the wrong answer?
#
# The all-five build does not crash, but every protected call reports
# "opcode 0x20 out of range at +0" on the device: the decode walk fails on the first
# byte, so either the virtualized `permute_code` scrambled the store or the virtualized
# `unpermute_code` cannot reproduce the mapping. `dvmp_body_tag` is the control - the
# body passes its authentication tag before the walk runs, so it is already proven good
# on the device (a wrong tag is a different error).
#
# One library per variant, all from the same unstripped build, each repacked, installed
# and screenshotted. Not a test-suite script: a device bisect, kept because the
# conclusion it produces is what the target list is allowed to contain.
#
# WHAT IT FOUND, so the next person does not have to re-run it:
#   * base3 (apply_keystream + keystream_seed + dvmp_body_tag) - all values correct, which
#     also proves the *unvirtualized* decode path was fine and put the fault on the two
#     instruction-stream targets.
#   * unperm + base3 - every protected call fails with "opcode 0x20 out of range at +0",
#     the decode walk rejecting the first byte, with the process alive.
#   * The difference between unpermute_code and the three working targets was CSEL (twice
#     in it, absent from all three), and removing it - by an exact identity for the
#     shuffle's remainder and two unconditional scatters for the inverse table - made the
#     whole five-target build correct on the device. See tool/vmpacker_targets.txt.
#
# Usage: powershell -ExecutionPolicy Bypass -File tool/bisect_vmpacker.ps1 -Only perm,unperm
[CmdletBinding()]
param(
  # Which variants to run, comma separated. The default is all three.
  #
  # A *string* rather than [string[]]: `powershell -File script.ps1 -Only perm,unperm`
  # passes the whole `perm,unperm` as one argument, so a [string[]] parameter received
  # @('perm,unperm') and every name failed to match - which silently ran zero variants
  # and still printed the trailer. Splitting it here makes both call styles work.
  [string]$Only = 'base3,perm,unperm'
)
$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
Push-Location $root
$wanted = @($Only.Split(',') | ForEach-Object { $_.Trim() } | Where-Object { $_ })

$adb = Join-Path $env:LOCALAPPDATA 'Android\Sdk\platform-tools\adb.exe'
if (-not (Test-Path $adb)) { throw "adb not found at $adb" }
$apk = 'app/build/app/outputs/flutter-apk/app-release.apk'
$so  = 'build/unstripped/libdartvmp.unstripped.arm64-v8a.so'
$pkg = 'com.dartvmp.dartvmp_demo'

# adb writes progress ("1 file pulled") and its daemon banner to stderr, and PowerShell
# turns native stderr into an error record that *terminates* the script while
# $ErrorActionPreference is Stop. Exactly this aborted the first run of this script
# after the first screenshot, with the pull having succeeded. Same helper as
# tool/verify_device_run.ps1, for the same reason.
function Invoke-Adb([string[]]$argv) {
  $prev = $ErrorActionPreference
  $ErrorActionPreference = 'Continue'
  try { return @(& $script:adb @argv 2>$null) } finally { $ErrorActionPreference = $prev }
}

$control = @('apply_keystream', 'keystream_seed', 'dvmp_body_tag')
$variants = [ordered]@{
  base3  = $control
  perm   = $control + @('permute_code')
  unperm = $control + @('unpermute_code')
}

foreach ($name in $variants.Keys) {
  if ($wanted -notcontains $name) { continue }
  Write-Host "== variant $name : $($variants[$name] -join ', ') ==" -ForegroundColor Cyan

  $tf = "build/targets_$name.txt"
  @('# generated by tool/bisect_vmpacker.ps1') + $variants[$name] +
    @('!op_tables', '!sm_next', '!sm_init') | Set-Content -LiteralPath $tf -Encoding ascii

  $lib = "build/lib_$name.so"
  powershell -NoProfile -ExecutionPolicy Bypass -File tool/apply_vmpacker.ps1 `
    -InputSo $so -OutputSo $lib -TargetsFile $tf *> "build/apply_$name.log"
  $coverage = (Get-Content "build/apply_$name.log") -match '^\s+translated '
  Write-Host "  apply: $($coverage -join ' | ')"

  powershell -NoProfile -ExecutionPolicy Bypass -File tool/repack_apk.ps1 -Apk $apk `
    -Replace "lib/arm64-v8a/libdartvmp.so=$lib" -Out "build/apk_$name.apk" *> "build/repack_$name.log"

  $install = Invoke-Adb @('install', '-r', "build/apk_$name.apk")
  # `-join` before matching: adb prints several lines ("Performing Streamed Install",
  # "Success") and `-notmatch` on an *array* returns the elements that do not match,
  # which is truthy for the "Performing ..." lines. That mistake made the first run of
  # this script report INSTALL FAILED for two installs that had succeeded.
  if (($install -join ' ') -notmatch 'Success') {
    Write-Host "  INSTALL FAILED: $($install -join ' / ')"
    continue
  }
  Invoke-Adb @('logcat', '-c') | Out-Null
  Invoke-Adb @('shell', 'am', 'force-stop', $pkg) | Out-Null
  Invoke-Adb @('shell', 'am', 'start', '-n', "$pkg/.MainActivity") | Out-Null
  Start-Sleep -Seconds 12
  Invoke-Adb @('shell', 'screencap', '-p', '/sdcard/dvmp.png') | Out-Null
  Invoke-Adb @('pull', '/sdcard/dvmp.png', "build/screen_$name.png") | Out-Null
  Invoke-Adb @('shell', 'rm', '/sdcard/dvmp.png') | Out-Null
  $faults = (Invoke-Adb @('logcat', '-d', '-t', '400')) |
    Select-String -Pattern 'FATAL|SIGSEGV|opcode 0x' | Select-Object -First 4 |
    ForEach-Object { $_.Line.Trim() }
  Write-Host "  screen: build/screen_$name.png"
  if ($faults) { Write-Host "  logcat: $($faults -join ' ;; ')" }
}

Write-Host ''
Write-Host 'Read the three screenshots. A variant whose demo card shows values (add(20,22)=42,' -ForegroundColor Yellow
Write-Host 'verifyLicense=true) is one whose every target computed correctly.' -ForegroundColor Yellow
Pop-Location
